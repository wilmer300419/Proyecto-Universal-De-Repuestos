-- V005: sesiones JWT y auditoría.
-- Cada JWT emitido queda registrado como una SESIÓN ligada a un usuario: el token solo vale si su sesión existe,
-- pertenece al usuario, no está revocada ni vencida y coincide con el navegador que la creó.
CREATE TABLE sesion_jwt (
    jti               VARCHAR(64) PRIMARY KEY,
    user_id           BIGINT NOT NULL REFERENCES app_user (user_id) ON UPDATE CASCADE ON DELETE CASCADE,
    emitido_en        TIMESTAMPTZ NOT NULL DEFAULT now(),
    expira_en         TIMESTAMPTZ NOT NULL,
    ip                VARCHAR(45),
    agente_hash       CHAR(64) NOT NULL,
    revocado_en       TIMESTAMPTZ,
    motivo_revocacion VARCHAR(40),
    CONSTRAINT ck_sesion_fechas     CHECK (expira_en > emitido_en),
    CONSTRAINT ck_sesion_revocacion CHECK ((revocado_en IS NULL) = (motivo_revocacion IS NULL))
);
CREATE INDEX ix_sesion_usuario ON sesion_jwt (user_id, revocado_en);
CREATE INDEX ix_sesion_expira  ON sesion_jwt (expira_en);

CREATE TABLE auditoria (
    id_auditoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT REFERENCES app_user (user_id) ON DELETE SET NULL,
    username     VARCHAR(40),
    accion       VARCHAR(40) NOT NULL,
    entidad      VARCHAR(60),
    detalle      TEXT,
    ip           VARCHAR(45),
    fecha        TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_auditoria_fecha  ON auditoria (fecha DESC);
CREATE INDEX ix_auditoria_accion ON auditoria (accion);
