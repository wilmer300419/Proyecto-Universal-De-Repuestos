-- V004: ventas, pagos, entregas y facturación electrónica
CREATE TABLE sale (
    sale_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              BIGINT NOT NULL REFERENCES app_user (user_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    sale_type_id         BIGINT NOT NULL REFERENCES sale_type (sale_type_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    sale_state_id        BIGINT NOT NULL REFERENCES sale_state (sale_state_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    company_warehouse_id BIGINT NOT NULL REFERENCES company_warehouse (company_warehouse_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    customer_name        VARCHAR(200) NOT NULL,
    description          VARCHAR(255),
    sale_date            TIMESTAMPTZ NOT NULL DEFAULT now(),
    subtotal             NUMERIC(14,2) NOT NULL DEFAULT 0,
    tax                  NUMERIC(14,2) NOT NULL DEFAULT 0,
    total                NUMERIC(14,2) NOT NULL DEFAULT 0,
    CONSTRAINT ck_sale_totales CHECK (subtotal >= 0 AND tax >= 0 AND total = subtotal + tax)
);
CREATE INDEX ix_sale_user  ON sale (user_id);
CREATE INDEX ix_sale_state ON sale (sale_state_id);
CREATE INDEX ix_sale_date  ON sale (sale_date DESC);

CREATE TABLE sale_detail (
    sale_detail_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id        BIGINT NOT NULL REFERENCES sale (sale_id) ON UPDATE CASCADE ON DELETE CASCADE,
    product_id     BIGINT NOT NULL REFERENCES product (product_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    quantity       INTEGER NOT NULL CHECK (quantity > 0),
    unit_price     NUMERIC(14,2) NOT NULL CHECK (unit_price >= 0),
    discount       NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (discount >= 0),
    subtotal       NUMERIC(14,2) NOT NULL CHECK (subtotal >= 0)
);
CREATE INDEX ix_sale_detail_sale ON sale_detail (sale_id);
CREATE INDEX ix_sale_detail_product ON sale_detail (product_id);

CREATE TABLE payment (
    payment_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id        BIGINT NOT NULL REFERENCES sale (sale_id) ON UPDATE CASCADE ON DELETE CASCADE,
    payment_date   TIMESTAMPTZ NOT NULL DEFAULT now(),
    amount         NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    method         VARCHAR(50) NOT NULL,
    reference      VARCHAR(100),
    status         VARCHAR(50) NOT NULL DEFAULT 'aprobado',
    receipt_issued BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_payment_method CHECK (method IN ('tarjeta_credito', 'tarjeta_debito', 'pse', 'transferencia', 'nequi', 'efectivo'))
);
-- Una venta solo puede tener un pago aprobado (evita el doble cobro a nivel de base de datos).
CREATE UNIQUE INDEX uq_payment_aprobado ON payment (sale_id) WHERE status = 'aprobado';

CREATE TABLE delivery (
    delivery_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id          BIGINT NOT NULL UNIQUE REFERENCES sale (sale_id) ON UPDATE CASCADE ON DELETE CASCADE,
    address          VARCHAR(255) NOT NULL,
    delivery_date    TIMESTAMPTZ,
    tracking_number  VARCHAR(100) UNIQUE,
    status           VARCHAR(50) NOT NULL DEFAULT 'pendiente',
    assigned_user_id BIGINT REFERENCES app_user (user_id) ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT ck_delivery_status CHECK (status IN ('pendiente', 'empacado', 'en_camino', 'entregado', 'cancelado'))
);
CREATE INDEX ix_delivery_assigned ON delivery (assigned_user_id, status);

CREATE TABLE electronic_invoice (
    invoice_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id        BIGINT NOT NULL UNIQUE REFERENCES sale (sale_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    invoice_number VARCHAR(100) NOT NULL UNIQUE,
    issue_date     TIMESTAMPTZ NOT NULL DEFAULT now(),
    subtotal       NUMERIC(14,2) NOT NULL,
    tax            NUMERIC(14,2) NOT NULL,
    total          NUMERIC(14,2) NOT NULL,
    qr_code        VARCHAR(500),
    pdf_path       VARCHAR(500),
    xml_path       VARCHAR(500),
    status         VARCHAR(50) NOT NULL DEFAULT 'emitida'
);

CREATE TABLE invoice_detail (
    invoice_detail_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id        BIGINT NOT NULL REFERENCES electronic_invoice (invoice_id) ON UPDATE CASCADE ON DELETE CASCADE,
    product_id        BIGINT NOT NULL REFERENCES product (product_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    quantity          INTEGER NOT NULL CHECK (quantity > 0),
    unit_price        NUMERIC(14,2) NOT NULL,
    discount          NUMERIC(14,2) NOT NULL DEFAULT 0,
    tax               NUMERIC(14,2) NOT NULL DEFAULT 0,
    subtotal          NUMERIC(14,2) NOT NULL
);
CREATE INDEX ix_invoice_detail_invoice ON invoice_detail (invoice_id);
