CREATE VIEW automotriz.v_entrega_detalle AS
 SELECT d.delivery_id,
    d.sale_id,
    d.address,
    d.delivery_date,
    d.tracking_number,
    d.status,
    d.assigned_user_id,
    r.username AS courier,
    s.customer_name,
    ss.name AS sale_state,
    s.sale_date,
    s.total
   FROM (((automotriz.delivery d
     JOIN automotriz.sale s ON ((s.sale_id = d.sale_id)))
     JOIN automotriz.sale_state ss ON ((ss.sale_state_id = s.sale_state_id)))
     LEFT JOIN automotriz.app_user r ON ((r.user_id = d.assigned_user_id)));


