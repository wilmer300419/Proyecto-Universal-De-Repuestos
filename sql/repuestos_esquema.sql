CREATE VIEW automotriz.v_ventas_por_estado AS
 SELECT ss.sale_state_id,
    ss.name AS state,
    (count(s.sale_id))::integer AS cantidad,
    COALESCE(sum(s.total), (0)::numeric) AS total
   FROM (automotriz.sale_state ss
     LEFT JOIN automotriz.sale s ON ((s.sale_state_id = ss.sale_state_id)))
  WHERE (ss.sale_state_id <= 5)
  GROUP BY ss.sale_state_id, ss.name;


