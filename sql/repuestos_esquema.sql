-- Name: v_productos_mas_vendidos; Type: VIEW; Schema: automotriz; Owner: -
--

CREATE VIEW automotriz.v_productos_mas_vendidos AS
 SELECT p.product_id,
    p.name,
    (sum(d.quantity))::integer AS cantidad,
    sum(d.subtotal) AS total
   FROM (((automotriz.sale_detail d
     JOIN automotriz.sale s ON ((s.sale_id = d.sale_id)))
     JOIN automotriz.sale_state ss ON ((ss.sale_state_id = s.sale_state_id)))
     JOIN automotriz.product p ON ((p.product_id = d.product_id)))
  WHERE ((ss.name)::text <> 'Cancelada'::text)
  GROUP BY p.product_id, p.name;


