CREATE VIEW automotriz.v_venta_resumen AS
 SELECT s.sale_id,
    s.user_id,
    u.username,
    s.sale_type_id,
    ss.name AS state,
    s.company_warehouse_id,
    s.customer_name,
    s.description,
    s.sale_date,
    s.subtotal,
    s.tax,
    s.total,
    (( SELECT COALESCE(sum(d.quantity), (0)::bigint) AS "coalesce"
           FROM automotriz.sale_detail d
          WHERE (d.sale_id = s.sale_id)))::integer AS items,
    dv.status AS delivery_status,
    dv.tracking_number,
    ei.invoice_id
   FROM ((((automotriz.sale s
     JOIN automotriz.sale_state ss ON ((ss.sale_state_id = s.sale_state_id)))
     JOIN automotriz.app_user u ON ((u.user_id = s.user_id)))
     LEFT JOIN automotriz.delivery dv ON ((dv.sale_id = s.sale_id)))
     LEFT JOIN automotriz.electronic_invoice ei ON ((ei.sale_id = s.sale_id)));


