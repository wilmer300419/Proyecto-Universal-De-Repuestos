-- V001: catálogos de referencia (esquema automotriz, según el ERD)
CREATE TABLE document_type (
    document_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(100) NOT NULL UNIQUE,
    acronym          VARCHAR(20)  NOT NULL UNIQUE,
    state            BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE department (
    department_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL UNIQUE,
    description   VARCHAR(255),
    state         BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE city (
    city_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    state         BOOLEAN NOT NULL DEFAULT TRUE,
    department_id BIGINT NOT NULL REFERENCES department (department_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT uq_city_department UNIQUE (department_id, name)
);

CREATE TABLE car_brand (
    car_brand_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(100) NOT NULL UNIQUE,
    description  VARCHAR(255),
    state        BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE car_type (
    car_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL UNIQUE,
    description VARCHAR(255),
    state       BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE cylinder_capacity (
    cylinder_capacity_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 VARCHAR(100) NOT NULL UNIQUE,
    state                BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE spare_part_type (
    spare_part_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               VARCHAR(100) NOT NULL UNIQUE,
    description        VARCHAR(255),
    state              BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE spare_part_brand (
    spare_part_brand_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(100) NOT NULL UNIQUE,
    description         VARCHAR(255),
    state               BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE sale_type (
    sale_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(100) NOT NULL UNIQUE,
    description  VARCHAR(255),
    state        BOOLEAN NOT NULL DEFAULT TRUE
);

-- Los cinco primeros estados (Pendiente, Pagada, Despachada, Entregada, Cancelada) los usa la aplicación.
CREATE TABLE sale_state (
    sale_state_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(50) NOT NULL UNIQUE,
    description   VARCHAR(255),
    state         BOOLEAN NOT NULL DEFAULT TRUE
);
