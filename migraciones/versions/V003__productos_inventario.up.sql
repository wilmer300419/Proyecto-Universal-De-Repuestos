-- V003: productos, vehículos, repuestos e inventario
CREATE TABLE product (
    product_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(150) NOT NULL,
    description    VARCHAR(255),
    unit_price     NUMERIC(14,2) NOT NULL CHECK (unit_price >= 0),
    state          BOOLEAN NOT NULL DEFAULT TRUE,
    fk_car_product BIGINT[] NOT NULL DEFAULT '{}',      -- ids de car compatibles (como en el ERD)
    fk_spare_part  BIGINT                                -- FK diferida, se agrega al crear spare_part
);
CREATE INDEX ix_product_cars ON product USING GIN (fk_car_product);
CREATE INDEX ix_product_name ON product (lower(name));

CREATE TABLE car (
    car_id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id           BIGINT REFERENCES product (product_id) ON UPDATE CASCADE ON DELETE SET NULL,
    name                 VARCHAR(150) NOT NULL,
    chassis_number       VARCHAR(100) UNIQUE,
    model                VARCHAR(100),
    state                BOOLEAN NOT NULL DEFAULT TRUE,
    cylinder_capacity_id BIGINT NOT NULL REFERENCES cylinder_capacity (cylinder_capacity_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    car_brand_id         BIGINT NOT NULL REFERENCES car_brand (car_brand_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    car_type_id          BIGINT NOT NULL REFERENCES car_type (car_type_id) ON UPDATE CASCADE ON DELETE RESTRICT
);
CREATE INDEX ix_car_brand ON car (car_brand_id);

CREATE TABLE spare_part (
    spare_part_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id          BIGINT NOT NULL REFERENCES product (product_id) ON UPDATE CASCADE ON DELETE CASCADE,
    name                VARCHAR(150) NOT NULL,
    state               BOOLEAN NOT NULL DEFAULT TRUE,
    spare_part_type_id  BIGINT NOT NULL REFERENCES spare_part_type (spare_part_type_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    spare_part_brand_id BIGINT NOT NULL REFERENCES spare_part_brand (spare_part_brand_id) ON UPDATE CASCADE ON DELETE RESTRICT
);
CREATE INDEX ix_spare_part_type ON spare_part (spare_part_type_id);

ALTER TABLE product ADD CONSTRAINT fk_product_spare_part FOREIGN KEY (fk_spare_part)
    REFERENCES spare_part (spare_part_id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED;

CREATE TABLE inventory (
    inventory_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id           BIGINT NOT NULL REFERENCES product (product_id) ON UPDATE CASCADE ON DELETE CASCADE,
    company_warehouse_id BIGINT NOT NULL REFERENCES company_warehouse (company_warehouse_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    quantity_available   INTEGER NOT NULL DEFAULT 0,
    minimum_stock        INTEGER NOT NULL DEFAULT 0,
    maximum_stock        INTEGER NOT NULL DEFAULT 0,
    reorder_stock        INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT uq_inventory_product_warehouse UNIQUE (product_id, company_warehouse_id),
    CONSTRAINT ck_inventory_cantidades CHECK (quantity_available >= 0 AND minimum_stock >= 0
                                              AND maximum_stock >= 0 AND reorder_stock >= 0)
);
