-- V002: empresa, bodegas, personas y usuarios de la aplicación
CREATE TABLE company (
    company_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tax_id     VARCHAR(50)  NOT NULL UNIQUE,
    name       VARCHAR(150) NOT NULL,
    address    VARCHAR(255),
    phone      VARCHAR(30),
    cellphone  VARCHAR(30),
    email      VARCHAR(150),
    state      BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE company_warehouse (
    company_warehouse_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id           BIGINT NOT NULL REFERENCES company (company_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    name                 VARCHAR(150) NOT NULL,
    address              VARCHAR(255),
    state                BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX ix_warehouse_company ON company_warehouse (company_id);

CREATE TABLE person (
    person_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id          BIGINT NOT NULL REFERENCES city (city_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    document_type_id BIGINT NOT NULL REFERENCES document_type (document_type_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    first_name       VARCHAR(100) NOT NULL,
    second_name      VARCHAR(100),
    last_name        VARCHAR(100) NOT NULL,
    second_last_name VARCHAR(100),
    birth_date       DATE,
    identification   VARCHAR(30) NOT NULL UNIQUE,
    email            VARCHAR(150),
    phone_number     VARCHAR(30)
);

-- Rol y control de acceso: adiciones al ERD necesarias para la seguridad (ver V005).
CREATE TABLE app_user (
    user_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username          VARCHAR(40)  NOT NULL UNIQUE,
    email             VARCHAR(150) NOT NULL UNIQUE,
    password_hash     TEXT NOT NULL,
    status            BOOLEAN NOT NULL DEFAULT TRUE,
    person_id         BIGINT NOT NULL REFERENCES person (person_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    role              VARCHAR(20) NOT NULL DEFAULT 'cliente',
    intentos_fallidos SMALLINT NOT NULL DEFAULT 0,
    bloqueado_hasta   TIMESTAMPTZ,
    creado_en         TIMESTAMPTZ NOT NULL DEFAULT now(),
    ultimo_acceso     TIMESTAMPTZ,
    CONSTRAINT ck_app_user_role CHECK (role IN ('cliente', 'administrador', 'empacador', 'repartidor')),
    CONSTRAINT ck_app_user_username CHECK (username = lower(username) AND username ~ '^[a-z0-9._-]{3,40}$'),
    CONSTRAINT ck_app_user_intentos CHECK (intentos_fallidos >= 0)
);
CREATE INDEX ix_app_user_person ON app_user (person_id);
